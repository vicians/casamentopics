    $policy$;
  end if;

  if not exists (
    select 1
    from pg_policies
    where schemaname = 'storage'
      and tablename = 'objects'
      and policyname = 'Convidados podem enviar fotos do casamento'
  ) then
    execute $policy$
      create policy "Convidados podem enviar fotos do casamento"
